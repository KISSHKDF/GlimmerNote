/**
 * 拾光小册 · **开放性主观题**判据（零副作用共享模块，2026-11-28 立）
 *
 * 起因（用户 2026-11-27 原话）：
 *   「某学生，Y0021，这一类的题目，出成这样的错题，孩子是无法做的，你是怎么通过盲解的？
 *     这类题目，建议不要收录进题库了」
 *
 * 实测根因（Y0021 = 某学生语文「启示题」）：
 *   ① 这道题**没有唯一标准答案** —— 「这则小故事对你今后的学习有怎样的启示？请结合内容谈一谈。」
 *      孩子答什么都能沾边，怎么答都不算"错" ⇒ **孩子无法做**（既不知道什么算对，更不知道错在哪）。
 *   ② 但它**通过了双路盲解**：盲解子代理独立写出一段"学习不只要记住，也要思考、不耻下问"，
 *      与录入答案**语义相近** ⇒ 判"与录入答案一致" ⇒ 卡入库。
 *      ⇒ **盲解对开放题失效**：它验的是"能不能写出像样的答案"，不是"孩子的答案到底错在哪"。
 *   ③ 更糟的是**证据图失配**：Y0021 的 `原卷截图.jpg` 裁图框高度只有原图的 7.5%
 *      （normBox y=0.875..0.95），切到的**只有红笔写的标准答案那一行** ——
 *      题干没进图、孩子的黑笔答案也没进图 ⇒ 「孩子的错解（黑笔，原样保留在原卷截图.jpg）」是**空头支票**。
 *      （卡里的「孩子的错解」文字是转录的，图里根本没有。）
 *
 * ⇒ 本模块给出的判据：**这道题能不能被客观判定为"错"**。
 *   能判 ⇒ 收录（像 Y0016 作文有老师给分 40、Y0039 抄写笔误、都有客观依据）；
 *   不能判 ⇒ **拒收**（不是"提示"，是 A 级阻断）。
 *
 * ★ 为什么不能只看"题型标记词"：
 *   「启示」「谈一谈」这类词**不等于**不可判定 ——
 *   Y0016 是作文题，但卷面有**老师红笔给分（40 分）**⇒ 有客观依据 ⇒ 可判定 ⇒ 保留。
 *   反过来，一句客观题也可能被误标成开放题（题干里恰好有"结合"二字）。
 *   ⇒ 判据必须是**三条件同时成立**才判"不可判定"，且每条都要有卡面证据。
 *
 * ⚠ 本模块必须保持**零副作用**（不解析 argv、不读库根）—— 它被入库器与门禁工具 import。
 */

/* ------------------------------------------------------------------ *
 * ① 开放性题型**标记词**（只做"候选发现"，单独命中**不作数**）
 * ------------------------------------------------------------------ */

/** 题干里的开放性题型标记词（命中只说明"这题可能是开放题"，还要过 ② ③）。 */
export const OPEN_TYPE_WORDS = [
  '启示', '谈一谈', '谈谈', '谈看法', '说说你的', '说说', '你的看法', '你怎么看', '怎么看待',
  '结合内容', '结合全文', '简要分析', '概括并', '体会', '感想', '你认为', '写一写', '自拟',
  '拟写', '举出', '谈谈你的', '感受', '抒发', '写一段', '你的建议',
];

/** 命中开放性题型标记词的题干。 */
export function hasOpenTypeWord(stem) {
  const s = String(stem || '');
  return OPEN_TYPE_WORDS.some(w => s.includes(w));
}

/* ------------------------------------------------------------------ *
 * ② 有**客观判定依据**的信号（有任一 ⇒ 这题可判定，不阻断）
 * ------------------------------------------------------------------ */

/* ⚠ 判据的松紧是这道门禁的全部难点 —— 第一次写得太松，被 Y0021 直接穿过去：
 *   Y0021 的 `answerSourceNote` 里写着「孩子答案只答了『学习方法』与『虚心』，
 *   **漏掉『思考』与『不耻下问』两个采分点**」—— 出现「采分点」三个字，
 *   按"卡面提到采分点就算有客观依据"的口径 ⇒ Y0021 被判"有依据、可判定" ⇒ 门禁放行。
 *   但它**列出的那两个"采分点"是它自己复述的**，既没给评分细则出处，也没说"踩到几点算几分"，
 *   孩子拿到这张卡**仍然不知道自己错在哪**（正是用户报障的原话：「孩子是无法做的」）。
 *
 * ⇒ 收紧成两类**真正可机械判定**的依据：
 *   A 类：**具体分数 / 评分细则**（"得分 40"、"（2 分）"、"满 10 分"、"按…给分"）
 *        —— 老师给过分 ⇒ 有标准可比；
 *   B 类：**可枚举的采分点清单**（编号列表 / 逐项引号 / "要点一…要点二…" / "必须答出…"）
 *        —— 孩子能拿清单**逐条对照**自己有没有踩到。
 *   而"采分点"三字本身、"漏掉…两个采分点"这类**描述性说法** ⇒ **不算**依据（正是 Y0021 的形态）。
 */

/** A 类：具体分数 / 评分细则（有分数才算，"按采分点给分"这种没数字的不算）。 */
export const SCORE_GROUND_RE = [
  /得分\s*[：:]?\s*\d+/,               // 得分 40
  /\d+\s*分\s*[，,。；;、）)]/,          // 40 分、
  /满\s*\d+\s*分/,
  /[（(]\s*\d+\s*分\s*[）)]/,          // （2 分）
  /按.{0,10}(给分|评分|计分)/,
];

/** B 类：**可枚举的采分点清单** —— 孩子能拿它逐条对照自己。 */
export const ENUMERABLE_POINTS_RE = [
  /要点\s*[一二三四1234]\s*[：:]/,          // 要点一：要…
  /\(\s*[1１]\s*\)\s*[^\n]{4,}/,           // (1) …(2) … 的分点罗列
  /[（(]\s*[1１]\s*[）)]\s*[^\n]{4,}/,
  /必须(答出|包含|写出|提到)/,             // 必须答出「…」
  /答[出到]?[「『"][^」』"]{2,24}[」』"]\s*(才|即|可|得|算)/,
  /[\u2460\u2461\u2462\u2463]/,             // ①②③④ 分点
];

/** 判据：卡面是否有**客观判定依据**（据此 ⇒ 这题可判定，不阻断收录）。
 *  @param {object} card  { question, answer, studentAnswer, causeNote, answerSourceNote, teacherAnswer, notes, recordText }
 *  @returns {{ok:boolean, why:string}} ok=true 表示"有客观依据，不阻断"。 */
export function hasObjectiveGround(card) {
  const c = card || {};
  /* 依据必须落在**与"正确与否"直接相关**的文本上：
   * 答案 / 「错在哪一步」/ 老师的判语 / 转录注。
   * ⚠ 刻意**不扫 `answerSourceNote`**（答案来源注记讲的是"我从哪儿查到的"，
   *   不是"凭什么判对错"）—— Y0021 的「漏掉…两个采分点」就写在那儿，扫了就会误放行。 */
  const hay = [
    c.answer, c.causeNote, c.teacherAnswer, c.recordText,
  ].filter(Boolean).join('\n');

  for (const re of SCORE_GROUND_RE) {
    if (re.test(hay)) return { ok: true, why: '卡面有**具体分数/评分细则**（' + re.source + '）⇒ 孩子有标准可比' };
  }
  for (const re of ENUMERABLE_POINTS_RE) {
    if (re.test(hay)) return { ok: true, why: '卡面有**可枚举的采分点清单**（' + re.source + '）⇒ 孩子能逐条对照' };
  }
  return { ok: false, why: '' };
}

/* ------------------------------------------------------------------ *
 * ③ 孩子答案"错在哪"**不可客观指认**的信号
 * ------------------------------------------------------------------ */

/** 「错在哪一步」只在说**笼统/主观**的信号。
 *  · "答得浅""没踩到采分点"在**没有采分点清单**时 = 不可判定（你无法机械验证"浅"）；
 *  · 但若同时有"客观依据"（② 已过），则按采分点判是允许的。
 */
export const VAGUE_CAUSE_RE = [
  /答得(浅|笼统|泛|不深|不到位)/,
  /过于(笼统|简单|宽泛)/,
  /泛泛/,
  /没(有)?(踩到|命中|答到|体现)(采分点|要点|关键)/,
  /漏(掉|了)?(采分点|要点)/,
  /空泛/,
];

/* ------------------------------------------------------------------ *
 * 主判据
 * ------------------------------------------------------------------ */

/**
 * 判定一张卡是否为「**不可客观判定的主观题**」——若是，**不得收录进错题库**。
 *
 * 三条件**同时成立**才判 true（缺一条都放行，避免误伤正常题）：
 *   ① 题干命中开放性题型标记词；
 *   ② 卡面**没有**任何客观判定依据（老师给分 / 红笔圈改 / 明确采分点）；
 *   ③ 「错在哪一步」落在笼统主观表述上（否则说明判错点其实是具体的）。
 *
 * @param {object} card 至少含 question（题干）；可选 answer / studentAnswer / causeNote /
 *                      answerSourceNote / teacherAnswer / notes / recordText（卡面全文）
 * @returns {{blocked:boolean, code:string, msg:string, evidence:string[]}}
 */
export function judgeOpenSubjective(card) {
  const c = card || {};
  const question = String(c.question || c.questionText || '');
  const evidence = [];

  if (!hasOpenTypeWord(question)) {
    return { blocked: false, code: '', msg: '', evidence };
  }
  evidence.push('题干命中开放性题型标记词：' + (OPEN_TYPE_WORDS.filter(w => question.includes(w)).join('、') || '—'));

  const ground = hasObjectiveGround(c);
  if (ground.ok) {
    return { blocked: false, code: '', msg: '', evidence: evidence.concat([ground.why]) };
  }
  evidence.push('卡面无客观判定依据（无老师给分 / 无红笔圈改 / 无明确采分点）');

  /* 「错在哪一步」在卡面哪里？优先 causeNote，其次卡面全文里的该段落。 */
  const cause = String(c.causeNote || '');
  const recordText = String(c.recordText || '');
  const causeSection = (() => {
    const m = /##\s*错在哪一步([\s\S]*?)(?=\n##\s|\n*$)/.exec(recordText);
    return m ? m[1] : cause;
  })();
  const hay = causeSection + '\n' + cause;

  const hit = VAGUE_CAUSE_RE.find(re => re.test(hay));
  if (!hit) {
    return {
      blocked: false, code: '', msg: '', evidence: evidence.concat(
        ['「错在哪一步」是**具体**的（未落在笼统主观表述上）⇒ 判错点可客观指认，本题可判定']),
    };
  }
  evidence.push('「错在哪一步」为笼统主观表述：' + hit.source);

  return {
    blocked: true,
    code: 'open-subjective',
    msg: '这是**没有唯一标准答案**的主观题，孩子无法判定自己对错（盲解能通过是因为它只验"能否写出像样答案"，' +
      '不验"孩子的答案错在哪"）⇒ 不得收录进错题库。请改录为：有明确采分点/老师给分/唯一解的子问；' +
      '或本题整体不入库。',
    evidence,
  };
}
